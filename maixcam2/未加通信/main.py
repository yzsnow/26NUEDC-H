def apply_env_overrides():
    """CTRL_OVERRIDE="kv_far=3.0,max_motor_deg=6" -- one tuning run, no file edit.

    Applied after load_config so a probe run wins over the saved file, and only
    for keys that already exist, so a typo is reported instead of quietly adding
    a config entry nothing reads.
    """
    spec = os.environ.get("CTRL_OVERRIDE", "").strip()
    if not spec:
        return
    for item in spec.split(","):
        if not item.strip():
            continue
        key, _, raw = item.partition("=")
        key = key.strip()
        if key not in CONFIG:
            print("override: unknown key", key)
            continue
        old = CONFIG[key]
        try:
            CONFIG[key] = int(raw) if isinstance(old, int) else float(raw)
        except ValueError:
            print("override: bad value for", key, raw)
            continue
        print("override: {} {} -> {}".format(key, old, CONFIG[key]))


