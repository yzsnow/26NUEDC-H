def sync_ctrl_from_config():
    ctrl.sync(CONFIG)
    # Direction and travel are facts about the machine, not tuning choices, so
    # they have exactly one editable copy (the MAIN page) and are mirrored into
    # TASK3's config one-way.  Two independent copies means one of them is
    # always stale, and a stale dir_invert does not merely control badly: the
    # beam drives the ball the wrong way, pins itself against the travel stop
    # and stalls, which browns the battery out and resets the board.
    for key in t3cfg.MIRRORED_FROM_MAIN:
        t3cfg.CONFIG[key] = CONFIG[key]
    motor.max_abs_deg = CONFIG["max_motor_deg"]


def drive_motor(theta_deg, omega_dps, now_ms, cfg):
    """Hand a controller's output to the driver in whichever mode it selected.

    cfg is the active mode's config: TASK3 carries its own drive_mode/rpm/acc so
    it can be driven harder than HOLD without touching HOLD's settings.
    """
    if cfg["drive_mode"]:
        motor.move_vel_dps(omega_dps, cfg["motor_acc"], now_ms)
    else:
        rpm = motor.rpm_for_dps(omega_dps, cfg["rpm_min"], cfg["motor_rpm"])
        motor.move_abs_deg(theta_deg, rpm, cfg["motor_acc"], now_ms)


def release_motor():
    """Leave a closed-loop mode: velocity mode would otherwise keep spinning."""
    motor.stop_now()


