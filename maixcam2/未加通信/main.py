def check_motor_link(timeout_ms=400):
    """Did the driver answer anything at all?  Returns True if a frame came back.

    Worth its own check because a dead RX line is indistinguishable from bad
    gains once the loop is running: the beam never moves, the ball never
    responds, and no fault is raised -- e2/ee stay 0 precisely BECAUSE nothing
    is being received.  A whole tuning session was spent on that mistake.

    0xF3 (enable) is used as the ping since it is idempotent and this firmware
    rejects the 0x36 position read.
    """
    before = motor.rx_count
    motor.enable(True)
    t_end = time.ticks_ms() + timeout_ms
    while time.ticks_ms() < t_end:
        motor.poll()
        if motor.rx_count > before:
            return True
        time.sleep_ms(10)
    return False


