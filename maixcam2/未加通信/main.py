"""Ball-and-beam controller for the 2026 NUEDC problem H swing arm.

Camera loop = outer control loop: YOLO26 ball detection -> alpha-beta filter ->
three-level cascade (ball position -> ball velocity -> beam angular velocity)
-> one ZDT Emm frame per update over UART.

The cascade is the whole point (see cascade.py): the motor does not set the
ball's position, it sets the tilt RATE, and tilt integrates into an angle which
produces acceleration which integrates twice into position.  Commanding tilt
rate instead of tilt angle means the static tilt that fights the mechanical zero
offset is generated by the loop structure, so the ball settles ON the target
rather than a few millimetres beside it, and the acceleration-damping term
brakes the ball before it reaches the setpoint instead of after.

Modes:
  IDLE       motor untouched, detection + display only
  HOLD       cascade keeps the ball at the beam center O (target 0 cm)
  TASK3      contest task 3: O -> +5 cm, turn around, -> -5 cm and settle
  SAFE_LOST  ball lost too long: beam ramps back to level until it returns

TASK3 runs on its OWN controller and its OWN parameter file (task3_ctrl.py +
task3_config.py -> /root/task3_config.json); HOLD and SAFE_LOST run on
cascade.py + the CONFIG below -> /root/ctrl_config.json.  The two never share a
gain, so tuning HOLD cannot move TASK3 and vice versa.  Their closed-loop laws
now use the same fast velocity estimate, braking cap, and far/near gain shape;
only their state, targets, and parameter values stay independent.  The tune
page's PAGE button switches between them.  The exceptions are wiring/mechanical facts
(direction, travel limit) which are mirrored one-way from here -- see
task3_config.MIRRORED_FROM_MAIN for why two copies of those is a trap.

Startup assumption: the beam is level at power-on; the motor position register
is cleared then (set_zero), so 0 deg always means level.
"""

