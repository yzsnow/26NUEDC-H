# ============================================================
# 4.1 开环播表段是怎么算出来的（标定只有一个数）
# ============================================================
#
# 每一段走位的倾角波形都关于自己的中点**反对称**：
#
#     θ
#     │      ┌──────┐                       r = ol_ramp_ms
#  +θ │     ╱        ╲                      T = 保持时长（解出来的）
#     │    ╱          ╲                     f = ol_flip_ms
#   0 │───┘     r  T   ╲f   T   r
#     │                 ╲          ╱
#  -θ │                  └────────┘
#         └─r─┘└T┘└──f──┘└T┘└─r─┘
#
# 反对称 => ∫a dt = 0 => **到点速度恒为零，与加速度大小无关**。
# 摩擦、电池电压、连杆比误差都动摇不了"停得下来"这件事，它们只影响"停在哪"。
# 这是开环敢用在走位段的唯一理由。
#
# 而"停在哪"有闭式解。设 A = 满倾角下的球加速度（就是 ol_a1/ol_a2），
# 逐段积分两次（推导见 task3_ctrl.OpenLoopPlan 的注释）得到
#
#     d = A · ( T² + T(r+f) + r²/3 + r·f/2 + f²/6 )
#
# 于是：
#   * 正向 —— 已知要走的距离 d，解一元二次方程得到 T，程序每次起跑自动算；
#   * 反向 —— 跑一次量出实际走了 d_实测，就能反解出真实的 A：
#
#         A_真 = A_设 × |d_实测| / |d_目标|
#
# 所以标定不是试凑两个毫秒值，而是**跑一趟、抄一个数**：跑完看日志里的
# `OL move1/move2` 两行，把它建议的 ol_a1_cms2 / ol_a2_cms2 填回去，第二趟就准了。
# 两段分开标是因为它们的速度不同、摩擦损耗占比不同，硬用一个数会有系统偏差。
#
# 起步估值：A ≈ (5/7)·g·sin(ol_theta_deg / 连杆比)。默认 9 电机度、连杆比 3
# （即摆杆 3°）算出来约 36.7 cm/s²，所以默认填 36。
#
# 加速度太大会走不了短距离：T 最小是 0，此时 d_min = A·(r²/3 + rf/2 + f²/6)，
# 默认参数下约 2.9 cm。要是 d_min 已经超过 5cm，程序会打印 `OL: 倾角过大`
# 并自动退回闭环 —— 这时该减小 ol_theta_deg，而不是去改斜坡。

# ============================================================
# 4.2 球速为什么不用主程序给的那个
# ============================================================
#
# main.py 传进来的 v_cms 来自 ball_position.AdaptiveAlphaBetaFilter，那里的速度
# 是**位置残差积出来的**：hat_v += beta·e/dt，而 beta 只有 0.01(静) ~ 0.12(动)。
# 时间常数约 1/beta 帧 —— 慢档下 8 帧，25fps 就是 **0.3 秒**。
# 位置本身跟得很好（alpha 到 0.95），只有速度这一路是陈的。
#
# 0.3 秒对位置环无所谓，对加速度阻尼是致命的：走位段交棒那一帧，球的真实速度
# 已经是 -0.06 cm/s（开环反对称波形保证的），观测器却还报 -5.9 cm/s。闭环于是
# 去"刹"一个根本不存在的速度，往回推倾角，球被推走，然后再追回来 —— 极限环。
#
# 所以控制器自己对位置差分（_ball_speed），只留一个一阶低通 v_lpf：
#
#     v_lpf = 1.0   完全不滤，最快，但把位置噪声整个放大 1/dt = 25 倍
#     v_lpf = 0.7   默认，约 1.4 帧时间常数
#     v_lpf = 0.4   噪声大时用，代价是加回约 2.5 帧滞后
#
# 差分的离群点保护复用 a_max_cms2 当每帧变化率上限，没有新参数。
# v_from_pos = 0 可以退回主程序那个速度做 A/B 对比 —— 但默认增益是按 1 调的，
# 切回 0 必须同时把带宽降下来，否则会自激。

# ============================================================
# 4.3 kp / kv / ka 只有一个自由度
# ============================================================
#
# 电机命令的是倾角**速度**，所以从 omega 到球位置是**三重积分**：
#
#     x'' = c·theta      c = 满倾角球加速度 / 倾角 ≈ 4.1 cm/s² 每电机度
#     theta' = omega
#
# 把控制律 omega = kv·(kp·err − v) − ka·a 代进去，闭环特征方程是
#
#     s³ + c·ka·s² + c·kv·s + c·kv·kp = 0
#
# 三个增益填的是同一个三次多项式的三个系数 —— 它们不是三个旋钮，是一个带宽
# ωn 的三个投影。按 Butterworth（s³ + 2ωn s² + 2ωn² s + ωn³）配极点：
#
#     ka = 2ωn/c        kv = 2ωn²/c        kp = ωn/2
#
# 默认 ωn = 3.0 rad/s，c = 4.08  ->  ka 1.5 / kv 4.4 / kp 1.5。
#
# 两条由此而来、跟直觉相反的结论：
#
# 1) **ka 不能调到 0**。没有 s² 项的三次多项式必然不稳定（Routh），跟 kv 多大
#    无关。离线扫参里 ka=0 那一列在每个 kv 上都跑飞，就是这个。ka 是这个环里
#    唯一的相位超前来源，只能定大小，不能取消。
# 2) **ωn 有上限，而且不高**。量测链（差分 + v_lpf + a_lpf + 半帧执行滞后）
#    在 ωn 附近就开始吃相位。离线扫参：ωn=3 最好，ωn=4 开始变差，
#    ωn=5 直接发散 —— 而 v2 的默认增益（kv 11 / ka 2.4 / kp 3.0）反解出来
#    正好是 ωn ≈ 5。那组值是在一个把球速当理想量的模型上调出来的。
#
# 要改速度就改 ωn 然后三个一起重算，别单独动一个：
#
#     ωn = 2.5 -> kp 1.25  kv 3.1  ka 1.2     稳但末端修正慢
#     ωn = 3.0 -> kp 1.50  kv 4.4  ka 1.5     默认
#     ωn = 3.5 -> kp 1.75  kv 6.0  ka 1.7     实物噪声很小时可以试
#
# a_lpf 同理有下限：它的极点在 a_lpf/dt，a_lpf=0.35 时是 8.8 rad/s，离 ωn 太近，
# 在穿越频率上贡献将近 50° 滞后。默认提到 0.5，别再往下调到 0.4 以下。

# ============================================================
# 4.4 起跑前为什么要等"摆杆也停住"（配平角）
# ============================================================
#
# 反对称保证"到点速度为零"只对**命令角产生的那部分加速度**成立。机械零点偏了
# z 度，就多出一个全程不变的偏置加速度 a_off = roll·g·sin(z/连杆比)，它不反对称，
# 一路积成 ½·a_off·T²。连杆比 2.5、z = 2° 时 a_off ≈ 9.8 cm/s²，move1 跑 1.4s
# 就多走 9cm —— 球直接出杆。这是开环走位唯一的致命项。
#
# 补偿办法：**抄闭环自己找到的平衡角**。ARM 段闭环托着球停在中心时，theta_cmd
# 稳定在 −z 附近，正好是抵消 a_off 需要的那个直流偏置，加到整张播放表上即可
# （见 task3_ctrl.OpenLoopPlan.theta_now）。不需要知道 z，也不需要量连杆比。
#
# 难点全在"什么时候抄"。ARM 段闭环在摩擦死区里**必然打极限环**（fric=1.5、
# 连杆比 3 时，球在 ±0.37° 摆杆角范围内都能静止不动，闭环无法收敛到一个点），
# 所以 theta_cmd 一直绕着真配平角摆。三次尝试的结果：
#
#   瞬时值 / 固定等待时长   arm_ms 1200/1500/2000/2500 -> 最坏 0.81/3.21/0.80/3.66
#                          非单调，纯粹是混叠 —— 固定时长等于在极限环周期上
#                          随机取相位。从这种数据里挑 arm_ms 是自欺欺人。
#   快慢双滤波器相交        更差（0.85~6.37）。慢滤波器要压住 1.1s 的周期，
#                          时间常数得 2s 以上，于是它从 0 爬到 3° 要 5 秒还没
#                          到位（实测 2.8s 时只到 2.3/3.0）；判据测的变成
#                          "滤波器追上了没"，而不是"配平稳了没"。而且两者在
#                          第一帧都是 0，闸门在启动瞬间大开，arm_ms=200 直接
#                          从这个假窗口溜出去，抄到配平角 0（最坏 5.47cm）。
#   滑窗平均 + 峰峰值判据   零偏 0/±1/±2/±3 下最坏 0.51/0.68/0.58/0.53cm。
#                          见 task3_ctrl.TRIM_WIN 和 TRIM_DEAD_DEG。
#
# 最后这套是：配平角取 32 帧滑窗的**时间平均**（对任何波形都无偏；(min+max)/2
# 只对对称波形成立，实测偶尔偏到 −1.59°/+5.06°），判据取同一窗口的**峰峰值**
# （= 极限环幅度，也就是"稳没稳"本身），窗口没盖满一个周期之前判据是 +∞。
#
# arm_trim_deg 就是那个峰峰值门槛。它和 arm_ms 要一起看：
#
#   arm_ms=200（默认）  阈值 0.8/1.2/1.8/2.5 -> 0.89/0.98/0.90/0.89cm  平的
#   arm_ms=800          同上阈值            -> 最坏 2.96cm
#   完全不要这个闸门     （阈值设 99）        -> 最坏 2.05cm
#
# 所以 arm_ms 取短、让峰峰值判据说了算，比"判据满足后再压一段固定时长"更稳：
# 在极限环里"连续满足很久"本来就难，压不住就落到 arm_max_ms 兜底，又回到随机
# 相位。arm_max_ms 只是防止"按了 TASK3 没反应"，不是正常路径。
#
# ---- arm_confirm=1（默认）：配平完不自动发车 ----
#
# 上面这一整套判据回答的是"配平收敛了没"，不是"人准备好了没"。自动发车把两件
# 事绑在了一起：配平判据一满足摆杆就动，而现场此时可能手还扶在球上、小车还没
# 摆好、或者根本是想先看一眼 `OL 配平` 打出来的角度合不合格再决定跑不跑。
#
# 所以默认改成两次按键：第一次进 ARM 做配平，判据满足（或走 arm_max_ms 兜底）
# 之后停在 READY，屏幕上出绿色大字 START；第二次按 TASK3 才发车，t0 也从这一帧
# 才起算。READY 段闭环照跑、目标仍是中心 O，所以球不会滚走，配平滑窗也一直在
# 刷新 —— 停在 READY 越久配平角越准，而这段等待不计入任务的 5 秒。
#
# arm_confirm=0 恢复"配平完自动发车"。arm_skip=1 时 arm_confirm 不起作用。
#
# ---- arm_skip=1：配平角改在 HOLD 段量 ----
#
# 上面整套判据的前提是"起跑前有一段闭环托着球停在中心"。arm_skip=1 把这一段
# 从 TASK3 里删掉了（球完全由人摆正，按键即起跑），于是配平角只能在别处量。
# 答案是 HOLD 段：它的目标同样恒为中心 O，平衡角同样等于 -机械零偏，唯一的
# 差别是增益不同 —— 而增益只改极限环的形状，不改它的均值，所以 32 帧滑窗照样
# 成立（Task3Controller.observe_trim）。
#
# 用这一档时现场动作是两步，顺序不能反：
#   1. 摆正球，按 HOLD，等两秒以上（32 帧 @20fps = 1.6s）—— 这一步在量配平角；
#   2. 手扶好球摆到起跑位，按 TASK3 —— 立刻起跑，带着刚量到的配平角。
# 跳过第 1 步不会拒跑，但日志会打"滑窗只有 n/32 帧，本趟不补配平角"，此时
# 机械零偏一点都补不掉，标定出来的 ol_a1/ol_a2 会分叉（一个偏小一个偏大）。
# 按 ZERO 会清空滑窗（reset_trim）—— 水平基准变了，旧的配平角就是错的。
#
# 另一条纪律：播表假设起跑速度为零。手还压着球或球还在滚就按 TASK3，那点初速
# 会原样加到落点上，而且它不进任何反馈，标定也补不回来。
#
# 剩下的极限：零偏 ±3° 时 ARM 段峰峰值稳态就有 5~8°（不是 0° 那档的 0.87°），
# 闭环压根没有安静的平衡点可抄，配平角精度只有 ±0.5°。连杆比 2.5 时 0.5° 折合
# move2 上约 2cm。**所以机械零点做准（MAIN 页 ZERO）比调这里任何一个数都值钱**，
# 目标是让日志里 `OL 配平` 打出来的角度落在 ±1° 以内。
#
# 而且这条极限直接决定了该开哪一套控制。216 工况按零偏分组（执行器 slew，
# 误差取球的真值）：
#
#   零偏      纯闭环 最坏/最长          双段标定3趟 最坏/最长
#    0°      1.73cm / 5.18s          0.97cm / 5.15s      <- 双段更准
#   +2°      1.28cm / 5.45s          1.09cm / 5.45s
#   -2°      1.32cm / 5.28s          3.43cm / 4.65s      <- 双段更快但明显更不准
#
# 闭环对零偏几乎不敏感（级联本身有积分作用，慢慢就把偏置吃掉了），开环没有
# 这个机制，配平补偿只能减轻不能消除（−2° 那档就是残留）。所以：
#
#   * 零点做得准（`OL 配平` 在 ±1° 内）-> 开双段（ol_enable=1），又快又准。
#   * 零点做不准、又来不及修机械 -> 关掉双段（OL ON = 0）走纯闭环，
#     牺牲的是时间（摩擦大的机器上可能跑到 5 秒以上甚至更久），换回精度。
#
# 别用调 TASK3 参数的办法去补机械零偏 —— 上面那张表说明这条路的上限就是 3~4cm。

