def save_runtime(path=RUNTIME_FILE):
    data = {"_ver": CONFIG_VERSION}
    for _en, _cn, key, _s, _lo, _hi in PARAM_TABLE:
        data[key] = CONFIG[key]
    with open(path, "w") as f:
        json.dump(data, f)


def load_runtime(path=RUNTIME_FILE):
    """恢复屏幕上存过的值。版本不符整个文件作废，不做逐项合并。"""
    if not os.path.exists(path):
        return False
    try:
        with open(path) as f:
            data = json.load(f)
    except Exception:
        return False
    if data.get("_ver") != CONFIG_VERSION:
        print("task3: 忽略过期存档 (want _ver", CONFIG_VERSION,
              "got", data.get("_ver"), ")", path)
        return False
    for _en, _cn, key, _s, _lo, _hi in PARAM_TABLE:
        if key in data:
            CONFIG[key] = data[key]
    return True


def apply_env_overrides():
    """TASK3_OVERRIDE="kv_near=13,v_max_cms=14" —— 单次试验，不改文件。

    在 load_runtime 之后调用，所以命令行永远压过存档；只认已存在的键，
    打错字会被报出来而不是悄悄新增一个没人读的配置项。
    """
    spec = os.environ.get("TASK3_OVERRIDE", "").strip()
    if not spec:
        return
    for item in spec.split(","):
        if not item.strip():
            continue
        key, _, raw = item.partition("=")
        key = key.strip()
        if key not in CONFIG:
            print("task3 override: 未知参数", key)
            continue
        old = CONFIG[key]
        try:
            CONFIG[key] = int(raw) if isinstance(old, int) else float(raw)
        except ValueError:
            print("task3 override: 数值非法", key, raw)
            continue
        print("task3 override: {} {} -> {}".format(key, old, CONFIG[key]))
